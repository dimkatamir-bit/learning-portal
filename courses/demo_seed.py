def _questions(Question, Choice, exam, items, database):
    for text, correct, wrong1, wrong2 in items:
        question, _ = Question.objects.using(database).get_or_create(exam=exam, text=text)
        for label, is_correct in ((correct, True), (wrong1, False), (wrong2, False)):
            Choice.objects.using(database).get_or_create(
                question=question, text=label, defaults={"is_correct": is_correct},
            )


def ensure_demo(Course, Module, Exam, Question, Choice, *, database="default"):
    """Создать или дополнить пример, сохраняя изменения администраторов и пользователей."""
    course, _ = Course.objects.using(database).get_or_create(
        title=TITLE, defaults={"description": DESCRIPTION},
    )
    for order, (title, content, questions) in enumerate(MODULES, 1):
        module, _ = Module.objects.using(database).get_or_create(
            course=course, order=order, defaults={"title": title, "content": content, "video_url": DEMO_VIDEOS[order - 1]},
        )
        if not module.video_url:
            Module.objects.using(database).filter(pk=module.pk, video_url="").update(video_url=DEMO_VIDEOS[order - 1])
        exam, _ = Exam.objects.using(database).get_or_create(
            module=module, defaults={"course": course, "is_final": False, "passing_score": 70},
        )
        if not Question.objects.using(database).filter(exam=exam).exists():
            _questions(Question, Choice, exam, questions, database)
    final, _ = Exam.objects.using(database).get_or_create(
        course=course, is_final=True, defaults={"passing_score": 70},
    )
    if not Question.objects.using(database).filter(exam=final).exists():
        _questions(Question, Choice, final, FINAL_QUESTIONS, database)
    return course
